#!/usr/bin/env python3
"""
Build the social share image (1200x630) for The $100 Guy Courses.

Written by hand rather than generated by an image model, for three reasons:
the typography is exact rather than garbled, it costs nothing, and it is
deterministic — the same input always yields the same image, so a rebuild can
never silently change the brand.

Design mirrors the site: deep navy ground, amber glow from the lower left, the
diamond mark, then the hierarchy of type.

    python3 _work/make-og-image.py
"""
from PIL import Image, ImageDraw, ImageFont, ImageFilter

W, H = 1200, 630
NAVY = (11, 17, 29)
NAVY_2 = (19, 24, 31)
GOLD = (241, 145, 29)
INK = (255, 255, 255)
MUTED = (154, 150, 150)
CREAM = (253, 248, 242)

FONT = "/usr/share/fonts/truetype/ubuntu/UbuntuSans[wdth,wght].ttf"
MONO = "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf"


def font(size, weight=400, width=100):
    f = ImageFont.truetype(FONT, size)
    try:
        f.set_variation_by_axes([width, weight])
    except Exception:
        pass
    return f


def lerp(a, b, t):
    return tuple(int(a[i] + (b[i] - a[i]) * t) for i in range(3))


def base():
    """Vertical navy gradient, slightly lighter toward the bottom."""
    img = Image.new("RGB", (W, H))
    d = ImageDraw.Draw(img)
    for y in range(H):
        d.line([(0, y), (W, y)], fill=lerp(NAVY, NAVY_2, y / H))
    return img


def glow(img):
    """Soft amber bloom from the lower-left, matching the site's radial glow."""
    layer = Image.new("RGB", (W, H), (0, 0, 0))
    d = ImageDraw.Draw(layer)
    for i in range(260, 0, -6):
        t = i / 260
        d.ellipse(
            [-320 - i, H - 420 - i, 620 + i, H + 220 + i],
            fill=lerp((0, 0, 0), GOLD, 0.055 * (1 - t)),
        )
    return Image.blend(img, Image.blend(img, layer, 0.55), 0.42).filter(
        ImageFilter.GaussianBlur(2)
    )


def mark(d, x, y, s):
    """The brand diamond — same geometry as app/icon.svg."""
    d.polygon([(x, y - s), (x + s, y), (x, y + s), (x - s, y)], fill=GOLD)
    inner = s * 0.52
    d.polygon(
        [(x, y - inner), (x + inner, y), (x, y + inner), (x - inner, y)],
        fill=NAVY,
    )


def text_w(d, s, f):
    return d.textlength(s, font=f)


def build() -> Image.Image:
    img = glow(base())
    d = ImageDraw.Draw(img, "RGBA")

    # faint diagonal streaks, echoing the site's light lines
    for i, off in enumerate(range(-200, 1400, 190)):
        d.line(
            [(off, H), (off + 420, 0)],
            fill=(255, 255, 255, 4 + (i % 3)),
            width=1,
        )

    LEFT = 112
    RIGHT = W - 112

    # ── brand row ──────────────────────────────────────────────────────────
    mark(d, LEFT + 40, 104, 40)
    d.text((LEFT + 100, 76), "THE $100 GUY", font=font(33, 700), fill=GOLD)
    d.text((LEFT + 100, 118), "COURSES", font=font(33, 400), fill=(255, 255, 255, 200))

    # ── headline ───────────────────────────────────────────────────────────
    d.text((LEFT, 210), "Digital Skills Courses", font=font(76, 800), fill=INK)
    d.text((LEFT, 300), "in Zambia", font=font(76, 300), fill=lerp(GOLD, CREAM, 0.15))

    # rule
    d.rectangle([LEFT, 414, LEFT + 120, 420], fill=GOLD)

    # ── supporting lines, as one left-aligned column ───────────────────────
    d.text(
        (LEFT, 446),
        "AI  ·  Facebook Ads  ·  Copywriting  ·  Graphic Design  ·  WordPress",
        font=font(28, 400),
        fill=(255, 255, 255, 220),
    )
    d.text(
        (LEFT, 494),
        "16 courses  ·  258 lessons  ·  from K150  ·  certificate on completion",
        font=font(26, 400),
        fill=(255, 255, 255, 155),
    )

    # ── sign-off, its own line, so it can never sit on the stats ───────────
    d.text((LEFT, 552), "Learn a skill. Use it. Get paid.", font=font(31, 600), fill=GOLD)

    # ── domain, bottom-right, kept clear of the column above ───────────────
    url = "georgekasonsocourses.vercel.app"
    uw = text_w(d, url, font(26, 500))
    d.text((RIGHT - uw, 578), url, font=font(26, 500), fill=(210, 206, 201))

    return img


if __name__ == "__main__":
    import os
    import sys

    out_dir = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "app")
    img = build()

    for name in ("opengraph-image.png", "twitter-image.png"):
        path = os.path.join(out_dir, name)
        img.save(path, "PNG", optimize=True)
        print(f"  wrote {path}  ({os.path.getsize(path)} bytes)")

    print(f"  size: {img.size}")
    sys.exit(0)
