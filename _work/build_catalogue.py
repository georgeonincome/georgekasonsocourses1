# ── write catalogue ────────────────────────────────────────────────────────
catalogue = []
for slug, title, category, level, price, duration, desc, curriculum in COURSES:
    lessons = []
    for topic_title, topic_lessons in curriculum:
        lessons.append({
            "title": topic_title,
            "lessons": list(topic_lessons),
        })
    catalogue.append({
        "slug": slug,
        "title": title,
        "subtitle": None,
        "description": desc,
        "price": price * 100,
        "compareAtPrice": None,
        "currency": "ZMW",
        "image": None,
        "images": [],
        "category": category,
        "level": level,
        "durationMinutes": duration,
        "sourceSlug": None,
        "sourceUrl": None,
        "isPublished": True,
        "isFeatured": slug in {
            "learn-to-earn",
            "ai-tool-mastery",
            "virtual-assistance-masterclass",
            "wordpress-web-design",
        },
        "enrollmentCount": 0,
        "curriculum": lessons,
    })

json.dump(catalogue, open(f"{OUT}/catalogue.json", "w"), indent=2, ensure_ascii=False)
json.dump(
    [{"slug": s, "name": n, "icon": i, "position": p}
     for p, (s, n, i) in enumerate(CATEGORIES)],
    open(f"{OUT}/categories.json", "w"), indent=2, ensure_ascii=False,
)

total_lessons = sum(len(l["lessons"]) for c in catalogue for l in c["curriculum"])
print(f"catalogue: {len(catalogue)} courses, {total_lessons} lessons")
print(f"categories: {len(CATEGORIES)}")
print(f"price range: K{min(c['price'] for c in catalogue) // 100} - "
      f"K{max(c['price'] for c in catalogue) // 100}")
